android {
    namespace = "com.kaskita.lokal"
    compileSdk = 36

    defaultConfig {
        applicationId = "com.kaskita.lokal"
        minSdk = 26
        targetSdk = 36
        versionCode = 1
        versionName = "1.0.0"
        testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
    }

    // Optional fixed App Check debug token (local.properties, git-ignored) so one console registration covers every phone.
    val appCheckToken = Properties().apply {
        val file = rootProject.file("local.properties")
        if (file.exists()) file.inputStream().use { load(it) }
    }.getProperty("appcheck.debugToken").orEmpty()
    defaultConfig {
        buildConfigField("String", "APPCHECK_DEBUG_TOKEN", "\"$appCheckToken\"")
    }

    // Signing secrets live in signing/keystore.properties (git-ignored). Without it, release stays unsigned.
    val signingProps = Properties().apply {
        val file = rootProject.file("signing/keystore.properties")
        if (file.exists()) file.inputStream().use { load(it) }
    }
    signingConfigs {
        if (signingProps.isNotEmpty()) {
            create("release") {
                storeFile = rootProject.file(signingProps.getProperty("storeFile"))
                storePassword = signingProps.getProperty("storePassword")
                keyAlias = signingProps.getProperty("keyAlias")
                keyPassword = signingProps.getProperty("keyPassword")
            }
        }
    }

    buildTypes {
        release {
            isMinifyEnabled = false
            signingConfigs.findByName("release")?.let { signingConfig = it }
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    buildFeatures {
        compose = true
        buildConfig = true
    }

    testOptions {
        unitTests {
            isIncludeAndroidResources = true
            isReturnDefaultValues = true
            all {
                // Robolectric (SDK 36) on JDK 21 touches JDK internals via reflection.
                it.jvmArgs("--add-opens=java.base/jdk.internal.access=ALL-UNNAMED")
            }
        }
    }
}

